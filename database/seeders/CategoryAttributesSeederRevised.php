        $categories = Category::query()->select('id', 'name', 'slug', 'parent_id')->get();
        $parentIds = $categories->pluck('parent_id')->filter()->unique()->all();
        $leaves = $categories->reject(fn ($c) => in_array($c->id, $parentIds, true));
        $missing = $leaves->reject(fn ($c) => isset($categoryTemplates[$c->slug]))->pluck('slug')->all();
        if ($missing !== []) {
            throw new RuntimeException('Missing attribute definitions for: '.implode(', ', $missing));
        }

        // Existing values are retained. Category links can be replaced safely in a transaction.
        DB::transaction(function () use ($leaves, $templates, $categoryTemplates): void {
            AttributeDefinitionService::lock();
            // Serialize cooperating seeders/editors, including the first run with no definitions.
            Category::whereIn('id', $leaves->pluck('id'))->orderBy('id')->lockForUpdate()->get();
            $attributeIds = [];
            foreach ($leaves as $category) {
                $definitions = $templates[$categoryTemplates[$category->slug]];
                $desired = [];
                foreach ($definitions as $sort => $definition) {
                    [$name, $type] = $definition;
                    $options = $definition[2] ?? null;
                    $unit = $definition[3] ?? null;
                    $optionsJson = $options === null ? null : json_encode($options, JSON_UNESCAPED_UNICODE);
                    $key = json_encode([$name, $type, $unit, $optionsJson], JSON_UNESCAPED_UNICODE);
                    if (! isset($attributeIds[$key])) {
                        $query = DB::table('attributes')->where('name', $name)->where('type', $type);
                        $unit === null ? $query->whereNull('unit') : $query->where('unit', $unit);
                        if ($unit !== null) {
                            $query->whereRaw('BINARY unit = BINARY ?', [$unit]);
                        }
                        if ($optionsJson === null) {
                            $query->whereNull('options');
                        } else {
                            $query->whereRaw('options = CAST(? AS JSON)', [$optionsJson]);
                        }
                        // Deterministic among existing duplicates; never merge by name alone.
                        $query->whereRaw('BINARY name = BINARY ?', [$name]);
                        $id = $query->orderBy('id')->value('id');
                        if (! $id) {
                            $id = DB::table('attributes')->insertGetId([
                                'name' => $name, 'type' => $type, 'options' => $optionsJson,
                                'unit' => $unit, 'is_filterable' => in_array($type, ['select', 'number', 'color'], true),
                                'created_at' => now(), 'updated_at' => now(),
                            ]);
                        }
                        $attributeIds[$key] = (int) $id;
                    }
                    $id = $attributeIds[$key];
                    DB::table('attributes')->where('id', $id)
                        ->where('is_filterable', '!=', in_array($type, ['select', 'number', 'color'], true))
                        ->update(['is_filterable' => in_array($type, ['select', 'number', 'color'], true)]);
                    $desired[] = $id;
                    DB::table('attribute_category')->updateOrInsert(
                        ['category_id' => $category->id, 'attribute_id' => $id],
                        ['sort_order' => $sort]
                    );
                }
                $obsolete = DB::table('attribute_category')->where('category_id', $category->id)
                    ->whereNotIn('attribute_id', $desired)->pluck('attribute_id')->all();
                AttributeHistory::detachFromCategory($category->id, $obsolete);
                DB::table('attribute_category')->where('category_id', $category->id)
                    ->whereIn('attribute_id', $obsolete)->delete();
            }
            DB::afterCommit(function () use ($leaves): void {
                foreach ($leaves as $category) {
                    CategoryFilterCacheService::clearForCategoryAndAncestors($category);
                }
                ReviewRatingCache::invalidate();
            });
        });
